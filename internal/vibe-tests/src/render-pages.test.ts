/**
 * @file Guards the family check pages against drift.
 * @input The family page modules, the built Core stylesheets, and the HTML
 *   files checked in beside those modules.
 * @output A failing test when a recorded value no longer resolves against the
 *   built sheets, or when a checked-in page no longer matches what the
 *   renderer produces.
 * @position internal/vibe-tests/src/render-pages.test.ts; companion to
 *   render-pages.ts and the `pages:render` script.
 *
 * The page a reviewer opens must show the values that ship. This test reads
 * them from `packages/core/dist` the same way the renderer does, so a stale
 * page fails here instead of misinforming a reviewer.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import {fileURLToPath} from 'node:url';
import {describe, expect, it} from 'vitest';
import {FAMILY_PAGES, renderFamilyPage} from './render-pages';

const PAGES_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../environments/project-astryx-tailwind/pages',
);

describe('family check pages', () => {
  for (const page of FAMILY_PAGES) {
    describe(`family:${page.family}`, () => {
      const rendered = renderFamilyPage(page);

      it('resolves every recorded value against the built sheets', () => {
        const failed = rendered.rows.filter(row => !row.ok);
        expect(failed.map(row => `${row.check.id}: ${row.reason}`)).toEqual([]);
        expect(rendered.rows.length).toBeGreaterThan(0);
      });

      it('ships a page that matches this render', () => {
        const file = path.join(PAGES_DIR, `${page.family}.html`);
        expect(fs.existsSync(file)).toBe(true);
        const html = fs.readFileSync(file, 'utf8');
        expect(html).toContain(rendered.markup);
        expect(html).toContain(
          'Generated by internal/vibe-tests/src/render-pages.ts',
        );
      });

      it('records the element each value is measured on', () => {
        for (const row of rendered.rows) {
          expect(row.check.element ?? row.check.id).toBeTruthy();
        }
      });
    });
  }
});
